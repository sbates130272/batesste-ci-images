def cmd_targets(args: argparse.Namespace) -> None:
    """Emit the CI build matrix.

    Both workflows call this instead of globbing for Dockerfiles and carrying
    their own exclusion lists, so which job builds what is decided in one place.
    """

    cfg = load_config(env_file=args.env_file)
    rows = []
    for t in discover_targets(cfg):
        job = str(target_attr(cfg, t, "job", "matrix"))
        if args.job and job != args.job:
            continue
        base = base_target(cfg, t)
        rows.append(
            {
                "key": t.key,
                "image": t.image,
                "variant": t.variant,
                "suffix": target_suffix(cfg, t),
                "scope": target_scope(cfg, t),
                "job": job,
                "artifact": bool(target_attr(cfg, t, "artifact", False)),
                "publish": publish_mode(cfg, t),
                "entitlement": needs_entitlement(cfg, t),
                # Lets the derived CI job point BASE_IMAGE at the copy of its
                # base built earlier in the same run without naming any image.
                "base": base.key if base else "",
                "base_scope": target_scope(cfg, base) if base else "",
            }
        )

    if args.json:
        print(json.dumps(rows, separators=(",", ":")))
        return
    print("\n".join(r["key"] for r in rows))


def cmd_validate(args: argparse.Namespace) -> None:
    """Check images.yml against the tree, and that everything renders."""

    cfg = load_config(env_file=args.env_file)
    errors: list[str] = []

    on_disk = {
        c.name
        for c in cfg.workdir.iterdir()
        if c.is_dir() and (c / "Dockerfile").is_file()
    }
    declared = set(cfg.spec.images)
    for missing in sorted(on_disk - declared):
        errors.append(f"{missing}/Dockerfile exists but {SPEC_FILE} has no entry")
    for missing in sorted(declared - on_disk):
        errors.append(
            f"{SPEC_FILE} declares {missing} but {missing}/Dockerfile is absent"
        )

    targets = discover_targets(cfg)  # also detects dependency cycles

    scopes: dict[str, str] = {}
    for t in targets:
        scope = target_scope(cfg, t)
        if scope in scopes:
            errors.append(f"{t.key} and {scopes[scope]} share the repository {scope}")
        scopes[scope] = t.key
        # Renders every template; render() exits on an unknown var or filter.
        image_variant(cfg, t)
        image_labels(cfg, t)
        build_args_for(cfg, t)
        # A mistyped retention key would otherwise surface as a prune run that
        # quietly used the defaults -- i.e. a wider policy than was written.
        try:
            prune_policy(cfg, t)
        except ValueError as exc:
            errors.append(str(exc))

    if errors:
        for e in errors:
            console.print(f"[red]Error:[/] {e}")
        sys.exit(1)
    source = SPEC_FILE
    if cfg.spec.overlay:
        source = f"{SPEC_FILE} + {OVERLAY_FILE}"
    console.print(f"[green]OK[/] {len(targets)} targets in {source}")


def _shields_escape(text: str) -> str:
    """Escape one path segment of a shields.io static badge.

    shields reads ``-`` as the field separator and ``_`` as a space, so both
    have to be doubled before the segment is percent-encoded.
    """

    return quote(text.replace("-", "--").replace("_", "__"), safe="")


def badge_markdown(cfg: Config) -> list[tuple[str, list[str]]]:
    """Render the badges: block of images.yml to ``(title, [markdown])`` rows.

    Every value is resolved through the same engine that renders tags and build
    args, so a badge cannot claim a pin the build does not use.
    """

    rows: list[tuple[str, list[str]]] = []
    for row in cfg.spec.badges.get("rows") or []:
        entries: list[str] = []
        for entry in row.get("entries") or []:
            label, var = entry["label"], entry["var"]
            target = parse_target(cfg, entry["target"])
            values = resolve_vars(cfg, target)
            if var not in values:
                console.print(
                    f"[red]Error:[/] badge '{label}' reads var '{var}', "
                    f"which {target.key} does not declare"
                )
                sys.exit(1)
            raw = str(values[var])
            if not raw:
                # An unset pin means the badge would advertise nothing. Better
                # to fail than to publish an empty shield.
                console.print(
                    f"[red]Error:[/] badge '{label}' reads var '{var}', "
                    f"which is empty on {target.key}"
                )
                sys.exit(1)

            shown = _dots(raw) if entry.get("dots") else raw
            if entry.get("short"):
                shown = _short(shown)

            img = (
                "https://img.shields.io/badge/"
                f"{_shields_escape(label)}-{_shields_escape(shown)}"
                f"-{entry.get('colour', 'blue')}"
            )
            badge = f"![{label} {shown}]({img})"
            # The link carries the full pin even when the badge shows a short
            # SHA, so it lands on the exact commit.
            if link := entry.get("link"):
                badge = f"[{badge}]({link.replace('{value}', raw)})"
            entries.append(badge)
        if entries:
            rows.append((row.get("title", ""), entries))
    return rows


def _github_slug(cfg: Config) -> str:
    """``owner/repo`` from defaults.metadata.source.

    Read rather than hardcoded so a fork's README badges point at the fork's
    own Actions runs.
    """

    source = str((cfg.spec.defaults.get("metadata") or {}).get("source", ""))
    slug = source.removeprefix("https://github.com/").strip("/")
    if slug.count("/") != 1:
        console.print(
            f"[red]Error:[/] defaults.metadata.source in {SPEC_FILE} is not a "
            f"github.com/<owner>/<repo> URL, so the build-status badges have "
            f"no repository to point at: {source!r}"
        )
        sys.exit(1)
    return slug


def status_table_rows(cfg: Config) -> list[tuple[str, str, str]]:
    """``(kind, label, job)`` per README row, in catalogue order.

    The bases job builds two targets at once and so collapses to a single row;
    everything else is one row per target, named by the repository it
    publishes to rather than by its target key, because the repository is what
    a reader is looking for.
    """

    rows: list[tuple[str, str, str]] = []
    bases: list[str] = []
    for t in discover_targets(cfg):
        kind = "qcow2" if publish_mode(cfg, t) == "artifact" else "container"
        if str(target_attr(cfg, t, "job", "matrix")) == "bases":
            bases.append(t.image)
            continue
        label = target_scope(cfg, t)
        # A variant's repository name does not say which job builds it, so
        # spell the target key out too.
        if t.variant:
            label = f"{label} (job: {t.key})"
        rows.append((kind, label, f"Build {t.key}"))

    if bases:
        rows.insert(
            0,
            (
                "container",
                f"{' + '.join(bases)} (shared base job)",
                STATUS_BASES_JOB,
            ),
        )
    return rows


def render_status_block(cfg: Config) -> str:
    """The marker-delimited per-artifact build-status table, markers included."""

    slug = _github_slug(cfg)
    query = f"?query=branch%3A{STATUS_BRANCH}+event%3A{STATUS_EVENT}"
    link = f"https://github.com/{slug}/actions/workflows/{STATUS_WORKFLOW}{query}"
    kinds = {"container": "1f6feb", "qcow2": "8957e5"}

    out = [
        STATUS_BEGIN,
        "",
        f"**Build by artifact on `{STATUS_BRANCH}`** (container and qcow2)",
        "",
        "| Artifact | main |",
        "| --- | --- |",
    ]
    for kind, label, job in status_table_rows(cfg):
        tag = f"[![{kind}](https://img.shields.io/badge/type-{kind}-{kinds[kind]})]"
        img = (
            f"https://img.shields.io/github/actions/workflow/status/{slug}/"
            f"{STATUS_WORKFLOW}?branch={STATUS_BRANCH}&event={STATUS_EVENT}"
            f"&job={quote(job, safe='')}"
        )
        name = label.split(" (")[0]
        out.append(f"| {tag} {label} | [![{name} {STATUS_BRANCH}]({img})]({link}) |")
    out += ["", STATUS_END]
    return "\n".join(out)


def render_badge_block(cfg: Config) -> str:
    """The full marker-delimited README section, markers included."""

    out = [BADGE_BEGIN]
    for title, entries in badge_markdown(cfg):
        out.append("")
        if title:
            out.append(f"**{title}**")
            out.append("")
        # One badge per line: Markdown still renders them on one row, and a
        # bump moves a single line rather than rewriting a paragraph.
        out.extend(entries)
    out.append("")
    out.append(BADGE_END)
    return "\n".join(out)


def _splice_block(text: str, begin: str, end: str, block: str, what: str) -> str:
    """Replace one marker-delimited section of the README."""

    start, stop = text.find(begin), text.find(end)
    if start == -1 or stop == -1:
        console.print(
            f"[red]Error:[/] {README_FILE} has no {what} markers. "
            f"Add these two lines where they belong:\n  {begin}\n  {end}"
        )
        sys.exit(1)
    return text[:start] + block + text[stop + len(end) :]


def cmd_badges(args: argparse.Namespace) -> None:
    """Regenerate, check, or print the README's generated shield blocks.

    Two sections, one command: the pinned-upstream badges, which come from the
    badges: block, and the per-artifact build-status table, which comes from
    the target list. A variant added to images.yml changes the second without
    touching the first, so checking only one of them is how the table drifted.
    """

    cfg = load_config(env_file=args.env_file)
    sections = [
        (BADGE_BEGIN, BADGE_END, render_badge_block(cfg), "pinned badge"),
        (STATUS_BEGIN, STATUS_END, render_status_block(cfg), "build status"),
    ]

    if args.stdout:
        print("\n\n".join(block for _, _, block, _ in sections))
        return

    readme = cfg.workdir / README_FILE
    text = readme.read_text()
    updated = text
    for begin, end, block, what in sections:
        updated = _splice_block(updated, begin, end, block, what)

    if updated == text:
        console.print(f"[green]OK[/] {README_FILE} badges match {SPEC_FILE}")
        return

    if args.check:
        console.print(
            f"[red]Error:[/] {README_FILE} badges are stale — a pin or a "
            f"target in {SPEC_FILE} changed without regenerating them.\n"
            f"Run: ./ci-images-tool.py badges --write"
        )
        sys.exit(1)

    readme.write_text(updated)
    console.print(f"[green]Updated[/] {README_FILE} badges from {SPEC_FILE}")


